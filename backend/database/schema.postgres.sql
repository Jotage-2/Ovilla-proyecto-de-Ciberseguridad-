BEGIN;

-- =========================================================
--  OVILLA - Estructura de la base de datos (PostgreSQL)
-- =========================================================

-- PostgreSQL aplica las claves foráneas automáticamente.


-- Usuarios: clientes y el dueño (rol 'admin')
CREATE TABLE public.usuarios (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        TEXT    NOT NULL,
  email         TEXT    NOT NULL UNIQUE,
  password_hash TEXT    NOT NULL,
  rol           TEXT    NOT NULL DEFAULT 'cliente' CHECK (rol IN ('cliente', 'admin')),
  creado_en     TEXT    NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

-- Categorías que aparecen en la barra lateral
CREATE TABLE public.categorias (
  id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE,
  slug   TEXT NOT NULL UNIQUE,
  icono  TEXT NOT NULL DEFAULT '🧶'
);

-- Cursos (gratuitos o de pago)
CREATE TABLE public.cursos (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo       TEXT    NOT NULL,
  descripcion  TEXT    NOT NULL DEFAULT '',
  autor        TEXT    NOT NULL,
  precio       DOUBLE PRECISION NOT NULL DEFAULT 0,
  es_gratis    INTEGER NOT NULL DEFAULT 0 CHECK (es_gratis IN (0, 1)),
  imagen       TEXT    NOT NULL DEFAULT '',
  nivel        TEXT    NOT NULL DEFAULT 'Principiante',
  duracion     TEXT    NOT NULL DEFAULT '',
  categoria_id INTEGER REFERENCES public.categorias(id) ON DELETE SET NULL,
  creado_en    TEXT    NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

-- Lecciones de cada curso (el contenido que se desbloquea)
CREATE TABLE public.lecciones (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  curso_id  INTEGER NOT NULL REFERENCES public.cursos(id) ON DELETE CASCADE,
  orden     INTEGER NOT NULL DEFAULT 1,
  titulo    TEXT    NOT NULL,
  contenido TEXT    NOT NULL DEFAULT '',
  video_url TEXT    NOT NULL DEFAULT ''
);

-- Compras: qué cliente compró qué curso
CREATE TABLE public.compras (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  curso_id   INTEGER NOT NULL REFERENCES public.cursos(id) ON DELETE CASCADE,
  monto      DOUBLE PRECISION NOT NULL,
  metodo     TEXT    NOT NULL DEFAULT 'tarjeta',
  referencia TEXT    NOT NULL DEFAULT '',
  creado_en  TEXT    NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
  UNIQUE (usuario_id, curso_id)
);

CREATE INDEX idx_cursos_categoria ON public.cursos(categoria_id);
CREATE INDEX idx_lecciones_curso  ON public.lecciones(curso_id);
CREATE INDEX idx_compras_usuario  ON public.compras(usuario_id);

-- Acceso por la API de Supabase requiere políticas RLS.
ALTER TABLE public.usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.categorias ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cursos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lecciones ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.compras ENABLE ROW LEVEL SECURITY;

COMMIT;
